test('PWA lädt offline, speichert einen Entwurf und schützt vor veralteter Eingabe', async ({ page, context }) => {
  await page.goto('/admin/volleyball-cup/spiel/1')
  await page.getByRole('button', { name: 'Spiel starten' }).click()
  await expect(page.getByText('Reguläre Spielzeit', { exact: true })).toBeVisible()
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller), undefined, { timeout: 10_000 })
  const manifest = await (await page.request.get('/manifest.webmanifest')).json()
  expect(manifest.display).toBe('standalone')
  expect(manifest.icons).toHaveLength(3)
  for (const icon of manifest.icons) expect((await page.request.get(icon.src)).headers()['content-type']).toContain('image/png')
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByText('Offline – Daten möglicherweise nicht aktuell.')).toBeVisible()
  await page.getByRole('spinbutton', { name: 'Punkte Team 01' }).fill('12')
  await page.getByRole('button', { name: 'Entwurf lokal speichern' }).click()
  await expect(page.getByText(/Entwurf lokal gespeichert/)).toBeVisible()
  await context.setOffline(false)
  await expect(page.getByRole('spinbutton', { name: 'Punkte Team 01' })).toHaveValue('12')
  const other = await context.newPage()
  await other.goto('/admin/volleyball-cup/spiel/1')
  await other.getByRole('button', { name: 'Pausieren' }).click()
  await expect(page.getByText(/Der Stand auf dem Server hat sich geändert/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Ergebnis einreichen' })).toBeDisabled()
})
